#!/usr/bin/env python3
"""Generate crates/script/src/js/reflect_table.js: the content-attribute
reflections ([Reflect], [ReflectURL], ...) declared in the HTML / ARIA IDL.

Usage: python3 tools/webapi/gen_reflect.py <idl_dir> > crates/script/src/js/reflect_table.js
"""
import json
import os
import sys

KINDS = {
    "DOMString": "s", "USVString": "s", "boolean": "b", "long": "l", "unsigned long": "ul",
    "double": "d", "unrestricted double": "d", "DOMTokenList": "t",
}


def ext(m, name):
    for a in m.get("extAttrs", []):
        if a["name"] == name:
            return a
    return None


def main():
    d = sys.argv[1]
    table = {}
    for spec in ("html", "wai-aria", "dom", "SVG2"):
        path = os.path.join(d, spec + ".json")
        if not os.path.exists(path):
            continue
        ip = json.load(open(path))["idlparsed"]
        items = []
        for name, n in ip["idlNames"].items():
            items.append((name, n))
        for name, lst in ip.get("idlExtendedNames", {}).items():
            for n in lst:
                if n["type"] != "includes":
                    items.append((name, n))
        for name, n in items:
            for m in n.get("members", []):
                if m.get("type") != "attribute":
                    continue
                refl = None
                for k in ("Reflect", "ReflectURL", "ReflectNonNegative", "ReflectPositive", "ReflectRange", "ReflectPositiveWithFallback", "ReflectSetter"):
                    if ext(m, k):
                        refl = k
                        break
                if not refl:
                    continue
                a = ext(m, "Reflect")
                attr = m["name"].lower()
                if a and a.get("rhs"):
                    attr = a["rhs"]["value"].strip('"')
                t = m["idlType"]["idlType"]
                if isinstance(t, list):
                    continue
                kind = KINDS.get(t)
                if refl == "ReflectURL":
                    kind = "u"
                if kind is None:
                    continue
                if refl in ("ReflectNonNegative",) and kind == "l":
                    kind = "nn"
                if refl in ("ReflectPositive", "ReflectPositiveWithFallback") and kind == "ul":
                    kind = "pos"
                dflt = ext(m, "ReflectDefault")
                entry = [m["name"], attr, kind]
                if dflt and dflt.get("rhs"):
                    entry.append(dflt["rhs"]["value"])
                if m.get("idlType", {}).get("nullable"):
                    entry.append("?")
                table.setdefault(name, []).append(entry)
    print("// Generated by tools/webapi/gen_reflect.py from the HTML/ARIA WebIDL. Do not edit.")
    print("// interface -> [[property, content attribute, kind, default?]]; kinds: s string,")
    print("// u URL, b boolean, l long, ul unsigned long, nn non-negative long, pos positive,")
    print("// d double, t DOMTokenList.")
    print("globalThis.__rhReflectTable = " + json.dumps(table, sort_keys=True, separators=(",", ":")) + ";")


if __name__ == "__main__":
    main()
